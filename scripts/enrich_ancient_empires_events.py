def main():
    data = json.loads(MAIN_PATH.read_text(encoding="utf-8"))
    all_texts = []
    for emp in data["empires"]:
        eid = emp["id"]
        if eid not in UPDATES:
            raise KeyError(f"Missing enrichment block for {eid}")
        upd = UPDATES[eid]
        emp["viewbox"] = upd["viewbox"]
        if "boundary_phases" in upd:
            emp["boundary_phases"] = upd["boundary_phases"]
        emp["events"] = upd["events"]
        assert len(emp["events"]) == 12, f"{eid} expected 12 events, got {len(emp['events'])}"
        for item in emp["events"]:
            assert item.get("shloka") and item["shloka"].get("text"), f"Missing shloka on {eid}/{item['title']}"
            all_texts.append((eid, item["title"], item["shloka"]["text"]))
        print(f"Enriched {eid:30s}: {len(emp['events'])} shloka-backed events | phases={len(emp['boundary_phases'])} | vb={emp['viewbox']}")

    # Enforce strict global uniqueness across all 120 classical shlokas
    seen = {}
    dups = []
    for eid, title, txt in all_texts:
        if txt in seen:
            dups.append((eid, title, seen[txt]))
        else:
            seen[txt] = (eid, title)
    assert not dups, f"Duplicate shlokas detected: {dups}"

    out_text = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    MAIN_PATH.write_text(out_text, encoding="utf-8", newline="\n")
    DOCS_PATH.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(MAIN_PATH, DOCS_PATH)
    print(f"\nTotal empires enriched: {len(data['empires'])}, total unique shloka events: {len(all_texts)}")


if __name__ == "__main__":
    main()
